"""Point-sample four independently generated jump poses; no synthetic motion edits."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import json, hashlib, statistics

ROOT=Path(__file__).resolve().parent
SOURCE=ROOT.parents[1]/'standing/source/native-idle/381-0.png'
OUT=ROOT/'381-jump-front-cycle-v1'
OUT.mkdir(exist_ok=True)
NAMES=['crouch','takeoff','apex','landing']
HEAD_WIDTH=[139,139,141,165]
HEAD_CENTER=[496.5,498.5,498.5,496.5]
BASE=181
W,H=128,192
frames=[]
records=[]
for n,name in enumerate(NAMES):
    path=ROOT/f'381-jump-front-{name}-generated-v1.png'
    raw=Image.open(path).convert('RGBA')
    bbox=raw.getchannel('A').point(lambda v:255 if v>=128 else 0).getbbox()
    scale=19/HEAD_WIDTH[n]
    reduced=raw.resize((round(raw.width*scale),round(raw.height*scale)),Image.Resampling.NEAREST)
    x=round(W/2-HEAD_CENTER[n]*scale)
    if name=='apex':
        y=round(16-bbox[1]*scale)
    else:
        clearance=6 if name=='takeoff' else 0
        y=round(BASE-clearance-bbox[3]*scale)
    target=Image.new('RGBA',(W,H))
    target.alpha_composite(reduced,(x,y))
    visible=target.getchannel('A').point(lambda v:255 if v>=128 else 0).getbbox()
    assert visible and visible[0]>0 and visible[1]>0 and visible[2]<W and visible[3]<H
    file=f'phase-{n}-{name}.png'
    target.save(OUT/file)
    frames.append(target)
    records.append({'phase':name,'frame':n,'file':file,'generatedSource':path.name,'generatedSha256':hashlib.sha256(path.read_bytes()).hexdigest(),'sha256':hashlib.sha256((OUT/file).read_bytes()).hexdigest(),'scale':scale,'scaleBasis':'head width matched to native19px; independent pose height is retained','headWidthGenerated':HEAD_WIDTH[n],'placement':[x,y],'alpha128Bounds':visible,'medianCutoutAlpha':statistics.median(v for v in target.getchannel('A').getdata() if v>=128)})
atlas=Image.new('RGBA',(W*4,H))
for n,im in enumerate(frames): atlas.paste(im,(n*W,0))
atlas.save(OUT/'atlas.png')
native=Image.new('RGBA',(W,H));native.alpha_composite(Image.open(SOURCE).convert('RGBA'),(24,16))
font=ImageFont.truetype('C:/Windows/Fonts/arial.ttf',15)
review=Image.new('RGB',(W*5*3,H*3+72),(42,45,49));draw=ImageDraw.Draw(review)
draw.text((12,8),'381 frontal jump — generated review candidate, not integrated or user-approved',font=font,fill='white')
for n,im in enumerate([native]+frames):
    cut=im.copy();cut.putalpha(cut.getchannel('A').point(lambda v:255 if v>=128 else 0))
    draw.text((n*W*3+12,35),(['Native standing']+NAMES)[n],font=font,fill='white')
    large=cut.resize((W*3,H*3),Image.Resampling.NEAREST)
    review.paste(large,(n*W*3,64),large)
    draw.line((n*W*3+8,64+BASE*3,(n+1)*W*3-8,64+BASE*3),fill=(100,100,100))
review.save(OUT/'contact-review.png')
animated=[]
for n,im in enumerate(frames):
    panel=Image.new('RGB',(W*3,H*3+45),(42,45,49));d=ImageDraw.Draw(panel)
    d.text((12,10),f'381 front jump | {NAMES[n]}',font=font,fill='white')
    cut=im.copy();cut.putalpha(cut.getchannel('A').point(lambda v:255 if v>=128 else 0))
    large=cut.resize((W*3,H*3),Image.Resampling.NEAREST)
    panel.paste(large,(0,40),large)
    animated.append(panel)
animated[0].save(OUT/'cycle-preview.gif',save_all=True,append_images=animated[1:],duration=[180,100,140,200],loop=0,disposal=2)
assert len({im.tobytes() for im in frames})==4
for n,im in enumerate(frames): assert atlas.crop((n*W,0,(n+1)*W,H)).tobytes()==im.tobytes()
manifest={'status':'generated-front-cycle-review-candidate','appearance':381,'state':'jumping','bearing':0,'bearingName':'front','framesPerBearing':4,'nativeSource':str(SOURCE),'nativeSourceSha256':hashlib.sha256(SOURCE.read_bytes()).hexdigest(),'nativeSourceSize':[73,165],'canvas':[W,H],'groundY':BASE,'frames':records,'technicalChecks':{'distinctPoses':4,'allFramesRgba':True,'noAlpha128Clipping':True,'atlasExact':True},'visualReview':'pending-contact-sheet-review','runtimeIntegrated':False,'userApproved':False,'exactNativePalette':False,'paletteProcessing':'none','reviewCutoutOnly':'Review panels simulate alpha>=128; deliverable frames retain sampled source alpha.','poseGeneration':'Four independently image-generated poses; no image translation presented as a new phase.','knownLimits':['Only frontal bearing complete; other seven directions not generated by this focused route.','Anatomical and temporal review required; four keyframes provide sparse motion.','Generated source changes some face/cloth pixels; exact pixel identity and palette not claimed.','Packing preserves body scale using head-width measurements, with contact baseline and6px takeoff clearance.']}
(OUT/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
print(json.dumps({'output':str(OUT),'frames':records,'technicalChecks':manifest['technicalChecks']},indent=2))
