atlas=Image.open(OUT/'atlas.png').convert('RGBA')
checks=[]
for entry in manifest['frames']:
    original,prompt,references=provenance[entry['source']]
    assert all((ROOT/reference).exists() for reference in references)
    source=ROOT/entry['source']
    assert source.read_bytes()==(raw/original).read_bytes()
    frame=Image.open(OUT/entry['file']).convert('RGBA')
    width,height=manifest['canvas']
    index=entry['index']
    assert frame.tobytes()==atlas.crop((index*width,0,(index+1)*width,height)).tobytes()
    bbox=frame.getchannel('A').point(lambda a:255 if a>=128 else 0).getbbox()
    assert bbox[0]>0 and bbox[1]>0 and bbox[2]<width and bbox[3]<height
    checks.append({'frame':entry['file'],'cutout_bounds':list(bbox),'no_clipping':True,
                   'raw_copy_unchanged':True,'frame_sha256':hashlib.sha256(frame.tobytes()).hexdigest()})
    entry.update({'visual_reviewed':True,'prompt':prompt,'generation_references':references,
                  'generation_method':'built-in imagegen single source-conditioned pose',
                  'raw_tool_output':str(raw/original)})
gif=Image.open(OUT/'preview.gif')
